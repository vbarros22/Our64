"""Writes player/source/covercodes.c: each N64 game code (the header's 4 bytes at
0x3B: cartridge type, 2-letter game id, country; "NZSE" is Majora's Mask USA)
with the No-Intro name libretro-thumbnails files its cover under. Our64 tries it
when a ROM's header CRCs are in no table (covertitles.c): a translated, patched
or otherwise changed ROM keeps its game code but gets new CRCs (2026-11-13:
Vinicius's Majora's Mask, Ocarina of Time, Donald Duck and F-1 World Grand Prix
II fetched no cover).

The inputs:
- libretro-database's No-Intro list for the N64 (clrmamepro format), whose
  games carry their serial (the game code), at libretro-database commit 5e01cef.
  https://github.com/libretro/libretro-database/blob/5e01cef/metadat/no-intro/Nintendo%20-%20Nintendo%2064.dat
- optional: the file names in libretro-thumbnails' Nintendo_-_Nintendo_64
  Named_Boxarts folder, one a line (git ls-tree --name-only HEAD Named_Boxarts/).
  A name with a cover there is picked before one without.

A code several releases share (Ocarina of Time's USA cart and its revisions,
the GameCube disc) gets one name: the one with a cover, then the plain retail
release (no Rev, Beta, Proto, Demo, GameCube, Virtual Console, Collection,
Debug or Kiosk tag), then the shortest, then the first by name.

    python3 -I tools/make-covercodes.py <No-Intro N64 .dat> [<boxart list>] > player/source/covercodes.c
"""
import re
import sys

TAGS = ("(Rev", "(Beta", "(Proto", "(Demo", "(Kiosk", "(Sample", "GameCube", "Virtual Console",
        "Collection", "(Debug", "Switch Online", "(Unl", "(Pirate", "(Aftermarket")


def read_dat(path):
    """game code -> its names, in the file's order."""
    text = open(path, encoding="utf-8").read()
    codes = {}
    for name, body in re.findall(r'game \(\s*name "([^"]*)"(.*?)\n\)', text, re.S):
        m = re.search(r'^\tserial "([^"]*)"', body, re.M)
        if not m or not re.fullmatch(r"[A-Z0-9]{4}", m.group(1)):
            continue
        names = codes.setdefault(m.group(1), [])
        if name not in names:
            names.append(name)
    return codes


def pick(names, covers):
    def key(n):
        return (covers is not None and n not in covers, sum(t in n for t in TAGS), len(n), n)
    return min(names, key=key)


def c_string(s):
    out = []
    for b in s.encode("utf-8"):
        c = chr(b)
        if c in '"\\':
            out.append("\\" + c)
        elif c == "?":
            out.append("\\?")
        elif 0x20 <= b < 0x7F:
            out.append(c)
        else:
            out.append("\\%03o" % b)
    return '"' + "".join(out) + '"'


def main():
    if len(sys.argv) not in (2, 3):
        print(__doc__, file=sys.stderr)
        return 2
    codes = read_dat(sys.argv[1])
    covers = None
    if len(sys.argv) == 3:
        covers = {l.strip()[:-4] for l in open(sys.argv[2], encoding="utf-8") if l.strip().endswith(".png")}
    print("/* Generated by tools/make-covercodes.py from libretro-database's No-Intro list:")
    print(" * the header's game code -> the No-Intro name libretro-thumbnails files its")
    print(" * cover under, for a ROM whose header CRCs are in no table. */")
    print('#include "covertitles.h"')
    print("static const covercode g_codes[] = {")
    without = 0
    for code in sorted(codes):
        name = pick(codes[code], covers)
        if covers is not None and name not in covers:
            without += 1
        print("\t{ %s, %s }," % (c_string(code), c_string(name)))
    print("};")
    print("const covercode *const covercodes = g_codes;")
    print("const unsigned covercodes_count = sizeof(g_codes) / sizeof(g_codes[0]);")
    print("// %d game codes%s" % (len(codes), "" if covers is None else ", %d without a cover" % without), file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
